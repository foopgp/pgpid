/* Decode one UTF-8 sequence, advancing *p. Returns the codepoint, or -1 on a
 * byte that is not valid UTF-8 — refused rather than reinterpreted, since a
 * mis-decoded name mints the wrong identifier. */
static long utf8_next(const unsigned char **p)
{
    const unsigned char *s = *p;
    unsigned c = *s;
    unsigned need;
    long cp;

    if (c < 0x80) { *p = s + 1; return c; }
    else if ((c & 0xE0) == 0xC0) { need = 1; cp = c & 0x1F; }
    else if ((c & 0xF0) == 0xE0) { need = 2; cp = c & 0x0F; }
    else if ((c & 0xF8) == 0xF0) { need = 3; cp = c & 0x07; }
    else return -1;

    for (unsigned i = 1; i <= need; i++) {
        if ((s[i] & 0xC0) != 0x80)
            return -1;
        cp = (cp << 6) | (s[i] & 0x3F);
    }
    *p = s + need + 1;
    return cp;
}

static const char *ascii_of(unsigned cp)
{
    size_t lo = 0, hi = sizeof MAP / sizeof *MAP;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (MAP[mid].cp == cp)
            return MAP[mid].ascii;
        if (cp < MAP[mid].cp)
            hi = mid;
        else
            lo = mid + 1;
    }
    return NULL;
}

int pgpid_transliterate(const char *in, char *out, size_t max)
{
    const unsigned char *p = (const unsigned char *)in;
    size_t o = 0;

    while (*p) {
        long cp = utf8_next(&p);
        if (cp < 0)
            return -1;

        /* Separators become the '<' the format uses, and runs squeeze into
         * one — done here, before transliteration, so the hyphen of
         * DE CLÉREL-DE-TOCQUEVILLE marks a boundary before it is spent. */
        if (cp == ' ' || cp == ';' || cp == ',' || cp == '-' || cp == '<') {
            if (o && o < max - 1 && out[o - 1] != '<')
                out[o++] = '<';
            continue;
        }

        if (cp < 0x80) {
            if (o < max - 1)
                out[o++] = (char)((cp >= 'a' && cp <= 'z') ? cp - 32 : cp);
            continue;
        }

        const char *ascii = ascii_of((unsigned)cp);
        if (!ascii)
            continue;   /* nothing the reference has an answer for */
        for (const char *a = ascii; *a && o < max - 1; a++)
            out[o++] = (char)((*a >= 'a' && *a <= 'z') ? *a - 32 : *a);
    }
    out[o] = '\0';
    return (int)o;
}
